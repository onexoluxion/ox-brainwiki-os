"""Generate THIRD_PARTY_NOTICES.md from the packages installed in the active environment.

Run from the repository root with the project interpreter:

    .venv/Scripts/python.exe tools/gen_notices.py

License resolution order per distribution: the ``License`` metadata field, else
``License-Expression``, else the first ``License ::`` classifier, else ``UNKNOWN``.
A multi-line ``License`` field (a pasted license body) is reported as ``see package``.
"""
from __future__ import annotations

import sys
from importlib import metadata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "THIRD_PARTY_NOTICES.md"

HEADER = """# Third-party notices

This file is generated by `tools/gen_notices.py` from the metadata of every
distribution installed in the project virtual environment (`uv sync --frozen
--python 3.12`, pinned in `uv.lock`). Regenerate it after any dependency change.
The license column is the package's own declaration; the full license texts
ship inside each installed distribution.

## Installed distributions

| Package | Version | License |
|---|---|---|
"""

