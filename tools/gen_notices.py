MCPVAULT = """
## MCPVault

MCPVault, copyright Mauricio Wolff / bitbonsai, MIT License,
https://github.com/bitbonsai/mcpvault. Architecture inspiration only: no MCPVault
code is copied into this repository, and no endorsement by its author is implied.
"""


def license_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    value = meta.get("License")
    if value and value.strip() and value.strip().upper() != "UNKNOWN":
        text = value.strip()
        return "see package" if "\n" in text else text
    expr = meta.get("License-Expression")
    if expr and expr.strip():
        return expr.strip()
    for classifier in meta.get_all("Classifier") or []:
        if classifier.startswith("License ::"):
            return classifier.split("::")[-1].strip()
    return "UNKNOWN"


def rows() -> list[tuple[str, str, str]]:
    seen: dict[str, tuple[str, str, str]] = {}
    for dist in metadata.distributions():
        name = dist.metadata.get("Name") or dist.name
        if not name:
            continue
        key = name.lower()
        if key in seen:
            continue
        seen[key] = (name, dist.version, license_of(dist))
    return sorted(seen.values(), key=lambda r: r[0].lower())


def main() -> int:
    table = rows()
    lines = [HEADER]
    for name, version, lic in table:
        lines.append(f"| {name} | {version} | {lic.replace('|', '/')} |\n")
    lines.append(f"\n{len(table)} distributions listed.\n")
    lines.append(BASIC_MEMORY)
    lines.append(MODEL)
    lines.append(MCPVAULT)
    OUTPUT.write_text("".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} with {len(table)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
